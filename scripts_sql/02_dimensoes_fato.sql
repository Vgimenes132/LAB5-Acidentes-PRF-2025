-- Parte 1. Dimensões preenchidas pela carga (script 03)

-- Localidade: município + UF, pois há nomes repetidos em estados diferentes.
CREATE TABLE dim_localidade (
    sk_localidade   NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1)
                    CONSTRAINT pk_dim_localidade PRIMARY KEY,
    nm_municipio    VARCHAR2(100 CHAR) NOT NULL,
    sg_uf           VARCHAR2(2   CHAR) NOT NULL,
    nm_uf           VARCHAR2(30  CHAR) NOT NULL,
    nm_regiao       VARCHAR2(20  CHAR) NOT NULL,
    CONSTRAINT uk_dim_localidade UNIQUE (nm_municipio, sg_uf)
);

-- Unidade da PRF: regional, delegacia e UOP.
CREATE TABLE dim_unidade_prf (
    sk_unidade_prf  NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1)
                    CONSTRAINT pk_dim_unidade_prf PRIMARY KEY,
    ds_regional     VARCHAR2(20 CHAR) NOT NULL,
    ds_delegacia    VARCHAR2(20 CHAR) NOT NULL,
    ds_uop          VARCHAR2(30 CHAR) NOT NULL,
    CONSTRAINT uk_dim_unidade_prf UNIQUE (ds_regional, ds_delegacia, ds_uop)
);

-- Causa do acidente
CREATE TABLE dim_causa (
    sk_causa        NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1)
                    CONSTRAINT pk_dim_causa PRIMARY KEY,
    ds_causa        VARCHAR2(200 CHAR) NOT NULL,
    CONSTRAINT uk_dim_causa UNIQUE (ds_causa)
);

-- Tipo de acidente
CREATE TABLE dim_tipo_acidente (
    sk_tipo_acidente NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1)
                     CONSTRAINT pk_dim_tipo_acidente PRIMARY KEY,
    ds_tipo_acidente VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT uk_dim_tipo_acidente UNIQUE (ds_tipo_acidente)
);

-- Condição meteorológica
CREATE TABLE dim_meteorologia (
    sk_meteorologia NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1)
                    CONSTRAINT pk_dim_meteorologia PRIMARY KEY,
    ds_meteorologia VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT uk_dim_meteorologia UNIQUE (ds_meteorologia)
);

-- Condição da via: junta quatro atributos pequenos em uma só dimensão.
CREATE TABLE dim_condicao_via (
    sk_condicao_via NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1)
                    CONSTRAINT pk_dim_condicao_via PRIMARY KEY,
    ds_fase_dia     VARCHAR2(30 CHAR) NOT NULL,
    ds_sentido_via  VARCHAR2(30 CHAR) NOT NULL,
    ds_tipo_pista   VARCHAR2(30 CHAR) NOT NULL,
    ds_uso_solo     VARCHAR2(10 CHAR) NOT NULL,
    CONSTRAINT uk_dim_condicao_via
        UNIQUE (ds_fase_dia, ds_sentido_via, ds_tipo_pista, ds_uso_solo)
);

-- Traçado da via: uma linha por combinação de itens, com um indicador S/N por item.
-- Evita contar o mesmo acidente duas vezes. Exemplo: WHERE fl_curva = 'S'.
CREATE TABLE dim_tracado (
    sk_tracado               NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1)
                             CONSTRAINT pk_dim_tracado PRIMARY KEY,
    ds_tracado               VARCHAR2(200 CHAR) NOT NULL,
    qt_itens                 NUMBER(2)          NOT NULL,
    fl_aclive                CHAR(1) DEFAULT 'N' NOT NULL,
    fl_curva                 CHAR(1) DEFAULT 'N' NOT NULL,
    fl_declive               CHAR(1) DEFAULT 'N' NOT NULL,
    fl_desvio_temporario     CHAR(1) DEFAULT 'N' NOT NULL,
    fl_em_obras              CHAR(1) DEFAULT 'N' NOT NULL,
    fl_intersecao_vias       CHAR(1) DEFAULT 'N' NOT NULL,
    fl_ponte                 CHAR(1) DEFAULT 'N' NOT NULL,
    fl_reta                  CHAR(1) DEFAULT 'N' NOT NULL,
    fl_retorno_regulamentado CHAR(1) DEFAULT 'N' NOT NULL,
    fl_rotatoria             CHAR(1) DEFAULT 'N' NOT NULL,
    fl_tunel                 CHAR(1) DEFAULT 'N' NOT NULL,
    fl_viaduto               CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT uk_dim_tracado UNIQUE (ds_tracado),
    CONSTRAINT ck_dim_tracado_flags CHECK (
        fl_aclive                IN ('S','N') AND fl_curva                 IN ('S','N') AND
        fl_declive               IN ('S','N') AND fl_desvio_temporario     IN ('S','N') AND
        fl_em_obras              IN ('S','N') AND fl_intersecao_vias       IN ('S','N') AND
        fl_ponte                 IN ('S','N') AND fl_reta                  IN ('S','N') AND
        fl_retorno_regulamentado IN ('S','N') AND fl_rotatoria             IN ('S','N') AND
        fl_tunel                 IN ('S','N') AND fl_viaduto               IN ('S','N'))
);


-- Parte 2. Dimensões geradas por script (incluem dias e horários sem acidente)

-- Data: chave no formato AAAAMMDD.
CREATE TABLE dim_data (
    sk_data         NUMBER(8)  CONSTRAINT pk_dim_data PRIMARY KEY,
    dt_data         DATE,
    nr_ano          NUMBER(4),
    nr_semestre     NUMBER(1),
    nr_trimestre    NUMBER(1),
    nr_mes          NUMBER(2),
    nm_mes          VARCHAR2(15 CHAR) NOT NULL,
    nm_mes_abrev    VARCHAR2(3  CHAR),
    ds_ano_mes      VARCHAR2(7  CHAR),
    nr_dia          NUMBER(2),
    nr_dia_semana   NUMBER(1),                    -- 1 = segunda, 7 = domingo
    nm_dia_semana   VARCHAR2(15 CHAR) NOT NULL,
    nr_semana_ano   NUMBER(2),
    fl_fim_semana   CHAR(1) DEFAULT 'N' NOT NULL
                    CONSTRAINT ck_dim_data_fds CHECK (fl_fim_semana IN ('S','N')),
    CONSTRAINT uk_dim_data UNIQUE (dt_data)
);

-- Dias de 2025. Para outros anos, trocar as duas datas.
INSERT INTO dim_data (
    sk_data, dt_data, nr_ano, nr_semestre, nr_trimestre, nr_mes, nm_mes,
    nm_mes_abrev, ds_ano_mes, nr_dia, nr_dia_semana, nm_dia_semana,
    nr_semana_ano, fl_fim_semana)
WITH dias AS (
    SELECT DATE '2025-01-01' + LEVEL - 1 AS dt
      FROM dual
   CONNECT BY LEVEL <= DATE '2025-12-31' - DATE '2025-01-01' + 1
), base AS (
    SELECT dt,
           EXTRACT(YEAR  FROM dt)       AS ano,
           EXTRACT(MONTH FROM dt)       AS mes,
           EXTRACT(DAY   FROM dt)       AS dia,
           TRUNC(dt) - TRUNC(dt, 'IW') + 1 AS dsem
      FROM dias
)
SELECT TO_NUMBER(TO_CHAR(dt, 'YYYYMMDD')),
       dt,
       ano,
       CASE WHEN mes <= 6 THEN 1 ELSE 2 END,
       CEIL(mes / 3),
       mes,
       CASE mes WHEN 1 THEN 'Janeiro'  WHEN 2 THEN 'Fevereiro' WHEN 3  THEN 'Março'
                WHEN 4 THEN 'Abril'    WHEN 5 THEN 'Maio'      WHEN 6  THEN 'Junho'
                WHEN 7 THEN 'Julho'    WHEN 8 THEN 'Agosto'    WHEN 9  THEN 'Setembro'
                WHEN 10 THEN 'Outubro' WHEN 11 THEN 'Novembro' WHEN 12 THEN 'Dezembro' END,
       CASE mes WHEN 1 THEN 'Jan' WHEN 2 THEN 'Fev' WHEN 3  THEN 'Mar' WHEN 4  THEN 'Abr'
                WHEN 5 THEN 'Mai' WHEN 6 THEN 'Jun' WHEN 7  THEN 'Jul' WHEN 8  THEN 'Ago'
                WHEN 9 THEN 'Set' WHEN 10 THEN 'Out' WHEN 11 THEN 'Nov' WHEN 12 THEN 'Dez' END,
       TO_CHAR(dt, 'YYYY-MM'),
       dia,
       dsem,
       CASE dsem WHEN 1 THEN 'segunda-feira' WHEN 2 THEN 'terça-feira'
                 WHEN 3 THEN 'quarta-feira'  WHEN 4 THEN 'quinta-feira'
                 WHEN 5 THEN 'sexta-feira'   WHEN 6 THEN 'sábado'
                 WHEN 7 THEN 'domingo' END,
       TO_NUMBER(TO_CHAR(dt, 'IW')),
       CASE WHEN dsem IN (6, 7) THEN 'S' ELSE 'N' END
  FROM base;

-- Horário: uma linha por minuto. Chave = minuto do dia + 1 (00:00 = 1).
CREATE TABLE dim_horario (
    sk_horario        NUMBER(4)  CONSTRAINT pk_dim_horario PRIMARY KEY,
    nr_hora           NUMBER(2),
    nr_minuto         NUMBER(2),
    hr_formatada      VARCHAR2(5  CHAR) NOT NULL,
    ds_faixa_horaria  VARCHAR2(30 CHAR) NOT NULL,
    nr_ordem_faixa    NUMBER(1),
    CONSTRAINT uk_dim_horario UNIQUE (hr_formatada)
);

INSERT INTO dim_horario (sk_horario, nr_hora, nr_minuto, hr_formatada,
                         ds_faixa_horaria, nr_ordem_faixa)
WITH minutos AS (
    SELECT LEVEL - 1 AS m FROM dual CONNECT BY LEVEL <= 1440
)
SELECT m + 1,
       TRUNC(m / 60),
       MOD(m, 60),
       LPAD(TRUNC(m / 60), 2, '0') || ':' || LPAD(MOD(m, 60), 2, '0'),
       CASE WHEN TRUNC(m / 60) BETWEEN 0  AND 5  THEN 'Madrugada (00h-05h)'
            WHEN TRUNC(m / 60) BETWEEN 6  AND 11 THEN 'Manhã (06h-11h)'
            WHEN TRUNC(m / 60) BETWEEN 12 AND 17 THEN 'Tarde (12h-17h)'
            ELSE                                      'Noite (18h-23h)' END,
       CASE WHEN TRUNC(m / 60) BETWEEN 0  AND 5  THEN 1
            WHEN TRUNC(m / 60) BETWEEN 6  AND 11 THEN 2
            WHEN TRUNC(m / 60) BETWEEN 12 AND 17 THEN 3
            ELSE                                      4 END
  FROM minutos;


-- Parte 3. Tabela fato: uma linha por ocorrência, com o id da PRF como chave.
CREATE TABLE fato_acidente (
    id_ocorrencia     NUMBER(10) CONSTRAINT pk_fato_acidente PRIMARY KEY,
    -- chaves das dimensões
    sk_data           NUMBER(8) NOT NULL CONSTRAINT fk_fato_data        REFERENCES dim_data,
    sk_horario        NUMBER(4) NOT NULL CONSTRAINT fk_fato_horario     REFERENCES dim_horario,
    sk_localidade     NUMBER(6) NOT NULL CONSTRAINT fk_fato_localidade  REFERENCES dim_localidade,
    sk_unidade_prf    NUMBER(6) NOT NULL CONSTRAINT fk_fato_unidade_prf REFERENCES dim_unidade_prf,
    sk_causa          NUMBER(6) NOT NULL CONSTRAINT fk_fato_causa       REFERENCES dim_causa,
    sk_tipo_acidente  NUMBER(6) NOT NULL CONSTRAINT fk_fato_tipo        REFERENCES dim_tipo_acidente,
    sk_meteorologia   NUMBER(6) NOT NULL CONSTRAINT fk_fato_meteorologia REFERENCES dim_meteorologia,
    sk_condicao_via   NUMBER(6) NOT NULL CONSTRAINT fk_fato_condicao_via REFERENCES dim_condicao_via,
    sk_tracado        NUMBER(6) NOT NULL CONSTRAINT fk_fato_tracado     REFERENCES dim_tracado,
    -- local da ocorrência
    nr_br             NUMBER(3),
    nr_km             NUMBER(6,1),
    nr_latitude       NUMBER(12,10),
    nr_longitude      NUMBER(12,10),
    -- medidas
    qt_pessoas        NUMBER(4) DEFAULT 0 NOT NULL,
    qt_mortos         NUMBER(4) DEFAULT 0 NOT NULL,
    qt_feridos_leves  NUMBER(4) DEFAULT 0 NOT NULL,
    qt_feridos_graves NUMBER(4) DEFAULT 0 NOT NULL,
    qt_ilesos         NUMBER(4) DEFAULT 0 NOT NULL,
    qt_ignorados      NUMBER(4) DEFAULT 0 NOT NULL,
    qt_veiculos       NUMBER(4) DEFAULT 0 NOT NULL,
    dt_carga          DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT ck_fato_qt_nao_negativas CHECK (
        qt_pessoas >= 0 AND qt_mortos >= 0 AND qt_feridos_leves >= 0 AND
        qt_feridos_graves >= 0 AND qt_ilesos >= 0 AND qt_ignorados >= 0 AND
        qt_veiculos >= 0)
);

COMMENT ON TABLE fato_acidente IS
  'Acidentes atendidos pela PRF, uma linha por ocorrência. Medidas derivadas (feridos, classificação, indicadores de qualidade) são calculadas nas views.';


